package com.kissene3.gui.interfaces;

import org.jetbrains.annotations.NotNull;

import java.awt.*;
import java.awt.event.MouseEvent;

/** The interface that must be implemented by components that handles other components internally. */
@SuppressWarnings("unused")
public interface Container {
	
	/**
	 * The method called when the mouse moves into the container.
	 * Called only if the component also implements {@link Hoverable}.
	 * @param e The {@link MouseEvent} of the motion.
	 */
	default void handleMouseMovement(@NotNull MouseEvent e) {}
	
	/**
	 * The method called when the container has to draw it's internal components.
	 * Called only if the component also implements {@link Drawable}.
	 * @param g The {@link Graphics} object.
	 * @param e The last event generated by the mouse.
	 */
	default void handleDraw(@NotNull Graphics2D g, @NotNull MouseEvent e) {}
}
