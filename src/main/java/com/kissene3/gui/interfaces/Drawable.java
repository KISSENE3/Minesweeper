package com.kissene3.gui.interfaces;

import org.jetbrains.annotations.Contract;
import org.jetbrains.annotations.NotNull;

import java.awt.*;
import java.awt.event.MouseEvent;

/** Interface that must be implemented by components that must be drawn to the screen. */
@SuppressWarnings("unused")
public interface Drawable {
	
	/**
	 * The method called when drawing something on the screen.
	 * @param g The {@link Graphics2D} object.
	 */
	void draw(@NotNull Graphics2D g);
	
	/**
	 * The method called when drawing the tooltip of the component.
	 *
	 * @param g The {@link Graphics2D} object.
	 * @param e The last event generated by the mouse.
	 */
	default void drawTooltip(@NotNull Graphics2D g, MouseEvent e) {}
	
	/** Gets the visible state of the component. */
	@Contract(pure = true)
	boolean isVisible();
	
	/** Sets the visible state of the component. */
	void setVisible(boolean visible);
}
